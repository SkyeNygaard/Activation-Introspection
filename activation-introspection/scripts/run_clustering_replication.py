"""notes/26 -- notes/19's clustering gate, on rules written by someone else.

notes/19 predicted which hidden rules a four-shot interface can learn, from class
separation alone, with the predictions frozen to disk first. It scored 12 of 14.
Its one obvious weakness is that Skye wrote all fourteen rules, so the set and the
hypothesis share an author.

These fourteen were generated by a different model through the Codex CLI, in a
read-only sandbox with the user's global instruction files excluded, from a prompt
that never mentions clustering, separation or learnability. The author is blind to
what is being tested. The prompt is saved next to the protocol.

**Thresholds are imported from ``run_clustering_prediction``, not restated**, so
this is an out-of-sample test of an already-registered rule rather than a new fit.
Same model, same layers, same design, same scoring.

    uv run python scripts/run_clustering_replication.py --phase measure
    uv run python scripts/run_clustering_replication.py --phase test

Phase ``test`` refuses to run before ``measure`` has frozen its predictions.
"""

